"""Select explicitly installed, trusted order adapters before creating resources.

Registration is discovery, not a sandbox. No installation, path imports, or network
fetch occurs here. Only the selected factory is imported; reports/recovery do not
call this module's loader.
"""

import csv
import hashlib
import importlib
import os
import re
import stat
import time
from importlib import metadata
from pathlib import Path, PurePosixPath

from faultline.adapters import AdapterError, CheckedAdapter, bundled_adapter, source_identity
from faultline.deadlines import DeadlineExceeded, alarm_until
from faultline.models import digest

ENTRY_POINT_GROUP = "faultline.adapters"
PREFLIGHT_SECONDS = 10
ENTRY_VALUE = re.compile(r"^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*:[A-Za-z_]\w*$", re.ASCII)


def _installed_entry(selection):
    # entry_points() deduplicates distributions by name. Two installed copies are
    # ambiguous provenance even when Python's import path would pick one of them.
    matches = []
    for index, distribution in enumerate(metadata.distributions()):
        if index >= 1024:
            raise ValueError("Installed distribution inventory exceeds discovery limit")
        entries = distribution.entry_points
        if len(entries) > 256:
            raise ValueError("Installed entry-point inventory exceeds discovery limit")
        matches.extend(
            entry
            for entry in entries
            if entry.group == ENTRY_POINT_GROUP and entry.name == selection.entry_point
        )
    if len(matches) != 1:
        raise ValueError("Adapter entry point must match exactly one installed registration")
    entry = next(iter(matches))
    if entry.dist is None or entry.dist.version != selection.package_version:
        raise ValueError("Adapter package_version must exactly match the installed distribution")
    if not ENTRY_VALUE.fullmatch(entry.value):
        raise ValueError("Adapter registration must use module:factory without extras")
    return entry


def _distribution_identity(entry):
    """Hash installed wheel files, not their unverified RECORD hash declarations.

    Editable installs and files outside the distribution root cannot establish the
    selected module's provenance under this small contract. Generated bytecode is
    excluded, and bytecode-only modules are refused.
    """
    distribution = entry.dist
    root = Path(distribution.locate_file("")).resolve(strict=True)
    # Python 3.13's Distribution.files silently filters missing files. Parse RECORD
    # itself so a damaged installation cannot receive a partial fingerprint.
    record = distribution.read_text("RECORD")
    if not record or len(record.encode("utf-8")) > 65536:
        raise ValueError("adapter requires a bounded wheel RECORD")
    files = list(csv.reader(record.splitlines()))
    if not files or len(files) > 256 or any(len(row) != 3 for row in files):
        raise ValueError("adapter requires a bounded installed file inventory")
    hashes, paths, seen, total = {}, {}, set(), 0
    for name, _record_hash, _record_size in files:
        relative = PurePosixPath(name)
        if (
            relative.is_absolute()
            or any(part in {"", ".", ".."} for part in name.split("/"))
            or "\\" in name
            or ":" in name
            or name in seen
        ):
            raise ValueError("adapter inventory contains an unsafe or duplicate path")
        seen.add(name)
        if relative.suffix in {".pyc", ".pyo"}:
            continue
        if relative.suffix in {".pth", ".so", ".pyd"}:
            raise ValueError("adapter requires a non-editable pure Python installation")
        path = root
        for part in relative.parts:
            path /= part
            if path.is_symlink():
                raise ValueError("adapter inventory cannot traverse symlinks")
        descriptor = os.open(path, os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW)
        with os.fdopen(descriptor, "rb") as stream:
            if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
                raise ValueError("adapter inventory requires regular files")
            raw = stream.read(1048577)
        total += len(raw)
        if len(raw) > 1048576 or total > 4194304:
            raise ValueError("adapter inventory exceeds size limit")
        paths[name] = path
        hashes[name] = hashlib.sha256(raw).hexdigest()
    module = entry.module.replace(".", "/")
    candidates = [name for name in (f"{module}.py", f"{module}/__init__.py") if name in paths]
    if len(candidates) != 1:
        raise ValueError("registered adapter module must be present as installed Python source")
    engine = source_identity()
    content = {"files": hashes, "engine_content_hash": engine["content_hash"], "entry": entry.value}
    identity = {
        "package": distribution.metadata["Name"],
        "package_version": distribution.version,
        "entry_point_group": ENTRY_POINT_GROUP,
        "entry_point": entry.name,
        "factory": entry.value,
        "source_hash_algorithm": "sha256-installed-files-and-engine-v1",
        "content_hash": digest(content),
        "files": hashes,
        "engine": engine,
    }
    return identity, paths[candidates[0]]


def _load_installed(selection):
    entry = _installed_entry(selection)
    try:
        identity, expected_source = _distribution_identity(entry)
    except Exception as exc:
        raise AdapterError(
            "identity", "adapter_contract_error", "Cannot establish installed adapter provenance"
        ) from exc
    try:
        factory = entry.load()
        module = importlib.import_module(entry.module)
        if Path(module.__file__).resolve(strict=True) != expected_source:
            raise ValueError("imported module differs from the installed inventory")
        adapter = CheckedAdapter(factory())
    except AdapterError:
        raise
    except Exception as exc:
        raise AdapterError("load", "adapter_hook_error", "Adapter factory failed") from exc
    if (
        adapter.description.adapter_id != selection.entry_point
        or not adapter.description.external_registration
    ):
        raise AdapterError(
            "describe", "adapter_contract_error", "Adapter description does not match registration"
        )
    return adapter, identity


def resolve_adapter(project=None, scenario=None, variant=None):
    """Return a fresh checked adapter and measured identity under one preflight alarm.

    The fixed allowance includes discovery, hashing, import, construction, describe,
    and validate. It is separate from run budgets, and starts before Docker/locking.
    Lifecycle hooks subsequently execute under the engine's existing stage alarms.
    """
    try:
        with alarm_until("adapter_preflight", time.monotonic() + PREFLIGHT_SECONDS, "stage"):
            selection = project.adapter if project else None
            if selection is None or selection.entry_point == "bundled_orders":
                adapter, identity = bundled_adapter(), source_identity()
            else:
                adapter, identity = _load_installed(selection)
            if project and not set(project.variants) <= set(adapter.description.variants):
                raise ValueError("Project variants require unsupported adapter capabilities")
            if project and any(
                service.readiness.check not in adapter.description.readiness_checks
                for service in project.services
            ):
                raise ValueError("Project requests an unregistered readiness check")
            if scenario is not None:
                adapter.validate(scenario, variant)
                if project:
                    from faultline.models import safe_path

                    routes = {route.id: route for route in project.routes}
                    for operation in scenario.all_operations:
                        route = routes.get(operation.route)
                        path = safe_path(operation.request.path)
                        if route is None or (
                            route.base_path != "/"
                            and path != route.base_path
                            and not path.startswith(route.base_path.rstrip("/") + "/")
                        ):
                            raise ValueError("operation escapes its declared application route")
            return adapter, identity
    except DeadlineExceeded as exc:
        raise AdapterError(
            "preflight",
            "adapter_preflight_timeout",
            "Adapter preflight exceeded its time allowance",
        ) from exc
